-- Storage lots and warehouse receipts.
--
-- The warehouse side. Withdrawals are a table of their own rather than a balance column on the lot,
-- because the licence requires the house to say when bushels left and not only how many are left.

CREATE TABLE storage_lot (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lot_id VARCHAR(24) NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    commodity_code VARCHAR(8) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    stored_on DATE NOT NULL,
    ticket_id INTEGER,
    closed_on DATE,
    billed_through DATE,
    accrued_to_date NUMERIC(14, 2) DEFAULT 0 NOT NULL,
    is_deferred_price BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_storage_lot PRIMARY KEY (id),
    CONSTRAINT fk_storage_lot_ticket_id_scale_ticket FOREIGN KEY (ticket_id) REFERENCES scale_ticket (id),
    CONSTRAINT uq_storage_lot_lot_id UNIQUE (lot_id),
    CONSTRAINT ck_storage_lot_bushels_positive CHECK (bushels > 0)
);
CREATE INDEX ix_storage_lot_party_code ON storage_lot (party_code, commodity_code);
CREATE INDEX ix_storage_lot_stored_on ON storage_lot (stored_on);

CREATE TABLE storage_withdrawal (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lot_row_id INTEGER NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    withdrawn_on DATE NOT NULL,
    reason VARCHAR(24) DEFAULT 'settled' NOT NULL,
    settlement_number VARCHAR(24),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_storage_withdrawal PRIMARY KEY (id),
    CONSTRAINT fk_storage_withdrawal_lot_row_id_storage_lot
        FOREIGN KEY (lot_row_id) REFERENCES storage_lot (id) ON DELETE CASCADE,
    CONSTRAINT ck_storage_withdrawal_bushels_positive CHECK (bushels > 0)
);
CREATE INDEX ix_storage_withdrawal_withdrawn_on ON storage_withdrawal (withdrawn_on);

CREATE TABLE warehouse_receipt (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    receipt_number VARCHAR(24) NOT NULL,
    lot_row_id INTEGER NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    commodity_code VARCHAR(8) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    grade VARCHAR(8) NOT NULL,
    issued_on DATE NOT NULL,
    cancelled_on DATE,
    lienholder VARCHAR(60),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_warehouse_receipt PRIMARY KEY (id),
    CONSTRAINT fk_warehouse_receipt_lot_row_id_storage_lot FOREIGN KEY (lot_row_id) REFERENCES storage_lot (id),
    CONSTRAINT uq_warehouse_receipt_receipt_number UNIQUE (receipt_number),
    CONSTRAINT ck_warehouse_receipt_bushels_positive CHECK (bushels > 0)
);
CREATE INDEX ix_warehouse_receipt_party_code ON warehouse_receipt (party_code);
