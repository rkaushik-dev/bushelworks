-- Bins and bin readings.
--
-- Readings are a table of their own. The aeration log is a compliance record and the state asks what
-- the temperature was doing in the week before a load went out, which a single last reading column
-- cannot answer.

CREATE TABLE bin (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    bin_id VARCHAR(12) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    capacity_bushels NUMERIC(14, 4) NOT NULL,
    bushels NUMERIC(14, 4) DEFAULT 0 NOT NULL,
    commodity_code VARCHAR(8),
    moisture NUMERIC(7, 4),
    test_weight NUMERIC(7, 4),
    damage NUMERIC(7, 4),
    is_aerated BOOLEAN DEFAULT FALSE NOT NULL,
    out_of_service BOOLEAN DEFAULT FALSE NOT NULL,
    out_of_service_reason VARCHAR(120),
    last_turned_on DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_bin PRIMARY KEY (id),
    CONSTRAINT uq_bin_location_code UNIQUE (location_code, bin_id),
    CONSTRAINT ck_bin_capacity_positive CHECK (capacity_bushels > 0),
    CONSTRAINT ck_bin_bushels_not_negative CHECK (bushels >= 0),
    CONSTRAINT ck_bin_bushels_fit CHECK (bushels <= capacity_bushels)
);
CREATE INDEX ix_bin_commodity_code ON bin (commodity_code);

CREATE TABLE bin_reading (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    bin_row_id INTEGER NOT NULL,
    taken_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cable INTEGER DEFAULT 1 NOT NULL,
    temperature_c NUMERIC(7, 4) NOT NULL,
    moisture NUMERIC(7, 4),
    fan_running BOOLEAN DEFAULT FALSE NOT NULL,
    note VARCHAR(120),
    CONSTRAINT pk_bin_reading PRIMARY KEY (id),
    CONSTRAINT fk_bin_reading_bin_row_id_bin FOREIGN KEY (bin_row_id) REFERENCES bin (id) ON DELETE CASCADE,
    CONSTRAINT ck_bin_reading_temperature_range CHECK (temperature_c > -60 AND temperature_c < 90)
);
CREATE INDEX ix_bin_reading_taken_at ON bin_reading (taken_at);
