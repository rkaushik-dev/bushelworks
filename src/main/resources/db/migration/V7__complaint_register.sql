-- The complaint register.
--
-- Every column that names what the complaint is about may be empty, because which one is filled in
-- depends on who is complaining. The buyer names a sale, the producer names a ticket, and the
-- feedlot names neither.
--
-- probe_id is a plain string and not a foreign key on purpose. Retained samples are thrown out on a
-- rota and a complaint filed against one should not keep it on the shelf for ever.

CREATE TABLE complaint (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(24) NOT NULL,
    source VARCHAR(12) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    raised_on DATE NOT NULL,
    delivered_on DATE NOT NULL,
    party_code VARCHAR(24),
    bin_id VARCHAR(12),
    ticket_number VARCHAR(24),
    sale_number VARCHAR(24),
    probe_id VARCHAR(24),
    outcome VARCHAR(12) DEFAULT 'open' NOT NULL,
    credit NUMERIC(14, 2) DEFAULT 0 NOT NULL,
    closed_on DATE,
    note VARCHAR(400) DEFAULT '' NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_complaint PRIMARY KEY (id),
    CONSTRAINT uq_complaint_reference UNIQUE (reference),
    CONSTRAINT ck_complaint_credit_not_negative CHECK (credit >= 0),
    CONSTRAINT ck_complaint_raised_after_delivery CHECK (raised_on >= delivered_on)
);
CREATE INDEX ix_complaint_bin_id ON complaint (bin_id, raised_on);
CREATE INDEX ix_complaint_party_code ON complaint (party_code);
CREATE INDEX ix_complaint_outcome ON complaint (outcome, raised_on);

CREATE TABLE complaint_action (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    complaint_id INTEGER NOT NULL,
    sequence INTEGER NOT NULL,
    taken_on DATE NOT NULL,
    taken_by VARCHAR(40) NOT NULL,
    what VARCHAR(200) NOT NULL,
    CONSTRAINT pk_complaint_action PRIMARY KEY (id),
    CONSTRAINT fk_complaint_action_complaint_id_complaint
        FOREIGN KEY (complaint_id) REFERENCES complaint (id) ON DELETE CASCADE,
    CONSTRAINT uq_complaint_action_complaint_id UNIQUE (complaint_id, sequence)
);
