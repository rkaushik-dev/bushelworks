-- The ledger chart and journal.
--
-- The journal has no status column and no way to update a row, which is the shape the tables are
-- meant to have rather than something left to add later. A wrong entry is corrected by posting its
-- reverse, and reverses records which one it was correcting.
--
-- parent_code and account_code are plain strings, not foreign keys into ledger_account. The chart is
-- filed once per house and read as a whole, and a foreign key there would mean the account table has
-- to be populated before anything can be posted into the journal.

CREATE TABLE ledger_account (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(12) NOT NULL,
    name VARCHAR(80) NOT NULL,
    type VARCHAR(12) NOT NULL,
    parent_code VARCHAR(12),
    closes_to VARCHAR(12),
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_ledger_account PRIMARY KEY (id),
    CONSTRAINT uq_ledger_account_code UNIQUE (code),
    CONSTRAINT ck_ledger_account_type_is_known
        CHECK (type in ('asset', 'liability', 'equity', 'revenue', 'expense')),
    CONSTRAINT ck_ledger_account_not_its_own_parent CHECK (code <> parent_code)
);
CREATE INDEX ix_ledger_account_parent_code ON ledger_account (parent_code);

CREATE TABLE journal_entry (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number VARCHAR(24) NOT NULL,
    posted_on DATE NOT NULL,
    memo VARCHAR(200) DEFAULT '' NOT NULL,
    source VARCHAR(24) DEFAULT '' NOT NULL,
    source_reference VARCHAR(48) DEFAULT '' NOT NULL,
    reverses VARCHAR(24),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_journal_entry PRIMARY KEY (id),
    CONSTRAINT uq_journal_entry_number UNIQUE (number)
);
CREATE INDEX ix_journal_entry_posted_on ON journal_entry (posted_on, number);
CREATE INDEX ix_journal_entry_source ON journal_entry (source, source_reference);

CREATE TABLE journal_leg (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    entry_id INTEGER NOT NULL,
    sequence INTEGER NOT NULL,
    account_code VARCHAR(12) NOT NULL,
    side VARCHAR(6) NOT NULL,
    dollars NUMERIC(14, 2) NOT NULL,
    memo VARCHAR(120) DEFAULT '' NOT NULL,
    CONSTRAINT pk_journal_leg PRIMARY KEY (id),
    CONSTRAINT fk_journal_leg_entry_id_journal_entry
        FOREIGN KEY (entry_id) REFERENCES journal_entry (id) ON DELETE CASCADE,
    CONSTRAINT uq_journal_leg_entry_id UNIQUE (entry_id, sequence),
    CONSTRAINT ck_journal_leg_leg_is_positive CHECK (dollars > 0),
    CONSTRAINT ck_journal_leg_side_is_known CHECK (side in ('debit', 'credit'))
);
CREATE INDEX ix_journal_leg_account_code ON journal_leg (account_code);

CREATE TABLE ledger_period (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(7) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    closed BOOLEAN DEFAULT FALSE NOT NULL,
    closed_on DATE,
    closed_by VARCHAR(48) DEFAULT '' NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_ledger_period PRIMARY KEY (id),
    CONSTRAINT uq_ledger_period_code UNIQUE (code),
    CONSTRAINT ck_ledger_period_period_runs_forwards CHECK (ends_on >= starts_on)
);
CREATE INDEX ix_ledger_period_starts_on ON ledger_period (starts_on);
