-- Sales and shipments.
--
-- Destination weight and grade may be empty. The buyer's settlement arrives a fortnight after the
-- truck and a shipment without one is the normal state, not a half written row.

CREATE TABLE sale_contract (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number VARCHAR(24) NOT NULL,
    kind VARCHAR(12) NOT NULL,
    buyer VARCHAR(80) NOT NULL,
    destination VARCHAR(16) NOT NULL,
    carrier VARCHAR(8) DEFAULT 'truck' NOT NULL,
    commodity_code VARCHAR(8) NOT NULL,
    origin_code VARCHAR(12) NOT NULL,
    written_on DATE NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    shipped NUMERIC(14, 4) DEFAULT 0 NOT NULL,
    window_opens DATE NOT NULL,
    window_closes DATE NOT NULL,
    futures_symbol VARCHAR(12),
    futures_price NUMERIC(12, 4),
    basis NUMERIC(12, 4),
    flat_price NUMERIC(12, 4),
    tolerance_percent NUMERIC(7, 4) DEFAULT 2 NOT NULL,
    freight_per_bushel NUMERIC(12, 4) DEFAULT 0 NOT NULL,
    spec_max_moisture NUMERIC(7, 4) NOT NULL,
    spec_min_test_weight NUMERIC(7, 4) NOT NULL,
    spec_max_damage NUMERIC(7, 4) NOT NULL,
    spec_max_foreign NUMERIC(7, 4) NOT NULL,
    status VARCHAR(12) DEFAULT 'open' NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sale_contract PRIMARY KEY (id),
    CONSTRAINT uq_sale_contract_number UNIQUE (number),
    CONSTRAINT ck_sale_contract_bushels_positive CHECK (bushels > 0),
    CONSTRAINT ck_sale_contract_shipped_not_negative CHECK (shipped >= 0),
    CONSTRAINT ck_sale_contract_window_ordered CHECK (window_closes >= window_opens),
    CONSTRAINT ck_sale_contract_freight_not_negative CHECK (freight_per_bushel >= 0)
);
CREATE INDEX ix_sale_contract_buyer ON sale_contract (buyer, status);
CREATE INDEX ix_sale_contract_commodity_code ON sale_contract (commodity_code, window_closes);

CREATE TABLE shipment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sale_id INTEGER NOT NULL,
    reference VARCHAR(24) NOT NULL,
    shipped_on DATE NOT NULL,
    carrier_id VARCHAR(24),
    origin_pounds NUMERIC(12, 0) NOT NULL,
    origin_bushels NUMERIC(14, 4) NOT NULL,
    destination_pounds NUMERIC(12, 0),
    destination_bushels NUMERIC(14, 4),
    destination_grade VARCHAR(8),
    settled_on DATE,
    proceeds NUMERIC(14, 2),
    rejected BOOLEAN DEFAULT FALSE NOT NULL,
    rejection_reason VARCHAR(200),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_shipment PRIMARY KEY (id),
    CONSTRAINT fk_shipment_sale_id_sale_contract
        FOREIGN KEY (sale_id) REFERENCES sale_contract (id) ON DELETE CASCADE,
    CONSTRAINT uq_shipment_sale_id UNIQUE (sale_id, reference),
    CONSTRAINT ck_shipment_origin_pounds_positive CHECK (origin_pounds > 0)
);
CREATE INDEX ix_shipment_shipped_on ON shipment (shipped_on);
CREATE INDEX ix_shipment_carrier_id ON shipment (carrier_id);
