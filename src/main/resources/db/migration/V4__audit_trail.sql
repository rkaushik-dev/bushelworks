-- The audit trail.
--
-- Append only. No foreign keys on purpose: an audit row has to survive the document it describes
-- being voided and reissued, and a key would either block that or cascade the evidence away with it.

CREATE TABLE audit_entry (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    effective_on DATE,
    actor VARCHAR(60) DEFAULT 'system' NOT NULL,
    action VARCHAR(40) NOT NULL,
    document_kind VARCHAR(24) NOT NULL,
    document_number VARCHAR(24) NOT NULL,
    party_code VARCHAR(24),
    location_code VARCHAR(12),
    amount NUMERIC(14, 2),
    detail VARCHAR(400),
    request_id VARCHAR(32),
    CONSTRAINT pk_audit_entry PRIMARY KEY (id),
    CONSTRAINT ck_audit_entry_action_not_blank CHECK (length(action) > 0)
);
CREATE INDEX ix_audit_entry_recorded_at ON audit_entry (recorded_at);
CREATE INDEX ix_audit_entry_document ON audit_entry (document_kind, document_number);
CREATE INDEX ix_audit_entry_actor ON audit_entry (actor);
