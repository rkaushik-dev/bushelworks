-- Contract and settlement tables.
--
-- The trading side. A revision of its own because the scale house went live on weights alone for
-- the first fortnight, with settlement done on the old system, and the two had to coexist.

CREATE TABLE purchase_contract (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number VARCHAR(24) NOT NULL,
    kind VARCHAR(12) NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    commodity_code VARCHAR(8) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    written_on DATE NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    window_opens DATE NOT NULL,
    window_closes DATE NOT NULL,
    futures_symbol VARCHAR(12),
    futures_price NUMERIC(12, 4),
    basis NUMERIC(12, 4),
    flat_price NUMERIC(12, 4),
    tolerance_percent NUMERIC(7, 4) DEFAULT 2 NOT NULL,
    service_rate_per_bushel NUMERIC(12, 4) DEFAULT 0 NOT NULL,
    status VARCHAR(12) DEFAULT 'open' NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_purchase_contract PRIMARY KEY (id),
    CONSTRAINT uq_purchase_contract_number UNIQUE (number),
    CONSTRAINT ck_purchase_contract_bushels_positive CHECK (bushels > 0),
    CONSTRAINT ck_purchase_contract_window_ordered CHECK (window_closes >= window_opens),
    CONSTRAINT ck_purchase_contract_tolerance_range
        CHECK (tolerance_percent >= 0 AND tolerance_percent <= 25)
);
CREATE INDEX ix_purchase_contract_party_code ON purchase_contract (party_code, status);
CREATE INDEX ix_purchase_contract_window_closes ON purchase_contract (window_closes);

CREATE TABLE contract_application (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ticket_id INTEGER NOT NULL,
    contract_id INTEGER NOT NULL,
    bushels NUMERIC(14, 4) NOT NULL,
    applied_on DATE NOT NULL,
    reversed_on DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_contract_application PRIMARY KEY (id),
    CONSTRAINT fk_contract_application_ticket_id_scale_ticket
        FOREIGN KEY (ticket_id) REFERENCES scale_ticket (id),
    CONSTRAINT fk_contract_application_contract_id_purchase_contract
        FOREIGN KEY (contract_id) REFERENCES purchase_contract (id),
    CONSTRAINT uq_contract_application_ticket_id UNIQUE (ticket_id, contract_id),
    CONSTRAINT ck_contract_application_bushels_positive CHECK (bushels > 0)
);
CREATE INDEX ix_contract_application_applied_on ON contract_application (applied_on);

CREATE TABLE settlement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number VARCHAR(24) NOT NULL,
    settled_on DATE NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    gross NUMERIC(14, 2) NOT NULL,
    deductions NUMERIC(14, 2) NOT NULL,
    net NUMERIC(14, 2) NOT NULL,
    paid_on DATE,
    cheque_number VARCHAR(16),
    voided BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_settlement PRIMARY KEY (id),
    CONSTRAINT uq_settlement_number UNIQUE (number)
);
CREATE INDEX ix_settlement_party_code ON settlement (party_code, settled_on);
CREATE INDEX ix_settlement_settled_on ON settlement (settled_on);

CREATE TABLE settlement_line (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    settlement_id INTEGER NOT NULL,
    sequence INTEGER NOT NULL,
    kind VARCHAR(16) NOT NULL,
    code VARCHAR(24) NOT NULL,
    description VARCHAR(120) NOT NULL,
    dollars NUMERIC(14, 2) NOT NULL,
    quantity NUMERIC(14, 4),
    rate NUMERIC(12, 4),
    CONSTRAINT pk_settlement_line PRIMARY KEY (id),
    CONSTRAINT fk_settlement_line_settlement_id_settlement
        FOREIGN KEY (settlement_id) REFERENCES settlement (id) ON DELETE CASCADE,
    CONSTRAINT uq_settlement_line_settlement_id UNIQUE (settlement_id, sequence),
    CONSTRAINT ck_settlement_line_dollars_not_negative CHECK (dollars >= 0)
);

CREATE TABLE settlement_ticket (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    settlement_id INTEGER NOT NULL,
    ticket_id INTEGER NOT NULL,
    CONSTRAINT pk_settlement_ticket PRIMARY KEY (id),
    CONSTRAINT fk_settlement_ticket_settlement_id_settlement
        FOREIGN KEY (settlement_id) REFERENCES settlement (id) ON DELETE CASCADE,
    CONSTRAINT fk_settlement_ticket_ticket_id_scale_ticket
        FOREIGN KEY (ticket_id) REFERENCES scale_ticket (id),
    CONSTRAINT uq_settlement_ticket_settlement_id UNIQUE (settlement_id, ticket_id)
);
