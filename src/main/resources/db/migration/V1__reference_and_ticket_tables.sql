-- Reference and ticket tables.
--
-- The schema as it stood when the scale house went live. Every constraint carries the name the
-- naming convention gives it (pk_, uq_, fk_, ck_, ix_), which is what lets a later revision drop one
-- by name.

CREATE TABLE party (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(24) NOT NULL,
    name VARCHAR(120) NOT NULL,
    sort_name VARCHAR(120) NOT NULL,
    tax_id VARCHAR(24),
    state_code VARCHAR(2) DEFAULT 'KS' NOT NULL,
    address_line1 VARCHAR(80),
    address_line2 VARCHAR(80),
    city VARCHAR(60),
    postal_code VARCHAR(12),
    phone VARCHAR(24),
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    checkoff_exempt BOOLEAN DEFAULT FALSE NOT NULL,
    opened_on DATE,
    closed_on DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_party PRIMARY KEY (id),
    CONSTRAINT uq_party_code UNIQUE (code),
    CONSTRAINT ck_party_code_not_blank CHECK (length(code) > 0)
);
CREATE INDEX ix_party_sort_name ON party (sort_name);

CREATE TABLE location (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(12) NOT NULL,
    name VARCHAR(80) NOT NULL,
    state_code VARCHAR(2) NOT NULL,
    warehouse_licence VARCHAR(24),
    licensed_capacity INTEGER,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_location PRIMARY KEY (id),
    CONSTRAINT uq_location_code UNIQUE (code),
    CONSTRAINT ck_location_code_not_blank CHECK (length(code) > 0)
);

CREATE TABLE commodity (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(8) NOT NULL,
    name VARCHAR(60) NOT NULL,
    standard_test_weight NUMERIC(12, 4) NOT NULL,
    base_moisture NUMERIC(7, 4) NOT NULL,
    price_unit VARCHAR(4) DEFAULT 'BU' NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_commodity PRIMARY KEY (id),
    CONSTRAINT uq_commodity_code UNIQUE (code),
    CONSTRAINT ck_commodity_test_weight_positive CHECK (standard_test_weight > 0),
    CONSTRAINT ck_commodity_base_moisture_range CHECK (base_moisture > 0 AND base_moisture < 100)
);

CREATE TABLE document_counter (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    series VARCHAR(16) NOT NULL,
    year INTEGER NOT NULL,
    next_value INTEGER DEFAULT 1 NOT NULL,
    CONSTRAINT pk_document_counter PRIMARY KEY (id),
    CONSTRAINT uq_document_counter_series UNIQUE (series, year),
    CONSTRAINT ck_document_counter_next_value_positive CHECK (next_value >= 1)
);

CREATE TABLE split_agreement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    farm_code VARCHAR(24) NOT NULL,
    party_id INTEGER NOT NULL,
    percent NUMERIC(7, 4) NOT NULL,
    role VARCHAR(16) DEFAULT 'owner' NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_split_agreement PRIMARY KEY (id),
    CONSTRAINT fk_split_agreement_party_id_party FOREIGN KEY (party_id) REFERENCES party (id),
    CONSTRAINT uq_split_agreement_farm_code UNIQUE (farm_code, party_id, effective_from),
    CONSTRAINT ck_split_agreement_percent_range CHECK (percent > 0 AND percent <= 100)
);

CREATE TABLE scale_ticket (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ticket_number VARCHAR(24) NOT NULL,
    location_code VARCHAR(12) NOT NULL,
    scale_date DATE NOT NULL,
    commodity_code VARCHAR(8) NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    gross_pounds NUMERIC(12, 0) NOT NULL,
    tare_pounds NUMERIC(12, 0) NOT NULL,
    dockage_percent NUMERIC(7, 4) DEFAULT 0 NOT NULL,
    disposition VARCHAR(16) NOT NULL,
    contract_number VARCHAR(24),
    truck_id VARCHAR(16),
    driver VARCHAR(60),
    farm VARCHAR(60),
    field_name VARCHAR(60),
    remarks VARCHAR(200),
    voided BOOLEAN DEFAULT FALSE NOT NULL,
    settled BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_scale_ticket PRIMARY KEY (id),
    CONSTRAINT uq_scale_ticket_location_code UNIQUE (location_code, ticket_number),
    CONSTRAINT ck_scale_ticket_gross_at_least_tare CHECK (gross_pounds >= tare_pounds),
    CONSTRAINT ck_scale_ticket_tare_not_negative CHECK (tare_pounds >= 0),
    CONSTRAINT ck_scale_ticket_dockage_range CHECK (dockage_percent >= 0 AND dockage_percent < 100)
);
CREATE INDEX ix_scale_ticket_scale_date ON scale_ticket (scale_date);
CREATE INDEX ix_scale_ticket_party_code ON scale_ticket (party_code);
CREATE INDEX ix_scale_ticket_commodity_code ON scale_ticket (commodity_code, scale_date);

CREATE TABLE ticket_sample (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ticket_id INTEGER NOT NULL,
    factor VARCHAR(24) NOT NULL,
    value NUMERIC(7, 4) NOT NULL,
    instrument VARCHAR(24),
    CONSTRAINT pk_ticket_sample PRIMARY KEY (id),
    CONSTRAINT fk_ticket_sample_ticket_id_scale_ticket
        FOREIGN KEY (ticket_id) REFERENCES scale_ticket (id) ON DELETE CASCADE,
    CONSTRAINT uq_ticket_sample_ticket_id UNIQUE (ticket_id, factor),
    CONSTRAINT ck_ticket_sample_value_not_negative CHECK (value >= 0)
);

CREATE TABLE ticket_split (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ticket_id INTEGER NOT NULL,
    party_code VARCHAR(24) NOT NULL,
    percent NUMERIC(7, 4) NOT NULL,
    role VARCHAR(16) DEFAULT 'owner' NOT NULL,
    bushels NUMERIC(14, 4),
    CONSTRAINT pk_ticket_split PRIMARY KEY (id),
    CONSTRAINT fk_ticket_split_ticket_id_scale_ticket
        FOREIGN KEY (ticket_id) REFERENCES scale_ticket (id) ON DELETE CASCADE,
    CONSTRAINT uq_ticket_split_ticket_id UNIQUE (ticket_id, party_code),
    CONSTRAINT ck_ticket_split_percent_range CHECK (percent > 0 AND percent <= 100)
);
